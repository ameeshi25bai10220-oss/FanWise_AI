"""
AACI Fan Digital Twin – Simulation & Replay Engine
==================================================
Phase 5 – Stage 3: Fan Digital Twin Runtime Implementation

Provides deterministic replay and synthetic scenario generation for virtual twins.

CRITICAL ARCHITECTURE REQUIREMENT:
All synthetic simulation packets, events, and records generated by this module
are explicitly tagged with:
    provenance = "SYNTHETIC_SIMULATION"
Synthetic data MUST NEVER be presented as real hardware measurements.
"""

from datetime import datetime, timezone
import time
from typing import Any, Dict, List, Optional

from aaci_ml.system_architecture.digital_twin.constants import SYNTHETIC_SIMULATION_PROVENANCE_TAG
from aaci_ml.system_architecture.digital_twin.fan_digital_twin import FanDigitalTwin
from aaci_ml.system_architecture.digital_twin.transition_engine import StateTransitionRecord


class DigitalTwinSimulator:
    """
    Simulation and replay test harness for virtual FanDigitalTwins.
    Explicitly labels all generated signals as SYNTHETIC_SIMULATION.
    """

    def __init__(self, fan_id: str = "Simulated_Fan_1"):
        self.fan_id = fan_id

    def generate_synthetic_telemetry(
        self,
        temperature: float = 27.5,
        humidity: float = 55.0,
        fan_speed: int = 3,
        espent_wh: float = 12.5,
        light: Optional[float] = 250.0,
        co2: Optional[float] = 650.0,
        timestamp: Optional[float] = None,
        is_stale: bool = False,
        sensor_age_s: float = 10.0,
    ) -> Dict[str, Any]:
        """
        Generates a synthetic telemetry dictionary.
        Explicitly marked with SYNTHETIC_SIMULATION provenance.
        """
        ts = (
            datetime.fromtimestamp(timestamp, timezone.utc).isoformat()
            if timestamp is not None
            else datetime.now(timezone.utc).isoformat()
        )

        packet: Dict[str, Any] = {
            "fan_id": self.fan_id,
            "timestamp": ts,
            "timestamp_s": timestamp if timestamp is not None else time.time(),
            "temperature": temperature,
            "relative_humidity": humidity,
            "fan_speed": fan_speed,
            "espent_wh": espent_wh,
            "sensor_age_s": sensor_age_s if not is_stale else 350.0,
            "is_stale": is_stale,
            "provenance": SYNTHETIC_SIMULATION_PROVENANCE_TAG,
            "disclaimer": "SYNTHETIC DATA FOR SIMULATION TESTING ONLY. NOT REAL MEASUREMENTS.",
        }

        if light is not None:
            packet["light"] = light
        if co2 is not None:
            packet["co2"] = co2

        return packet

    def run_replay(
        self,
        twin: FanDigitalTwin,
        sequence: List[Dict[str, Any]],
        step_delay_s: float = 0.0,
    ) -> List[StateTransitionRecord]:
        """
        Deterministically replays a sequence of telemetry packets into a digital twin.
        Returns all transitions generated during the replay.
        """
        all_transitions: List[StateTransitionRecord] = []
        if sequence and "timestamp_s" in sequence[0]:
            twin.last_update_timestamp = float(sequence[0]["timestamp_s"])

        for packet in sequence:
            # Ensure provenance is strictly tagged
            prov = packet.get("provenance", SYNTHETIC_SIMULATION_PROVENANCE_TAG)
            transitions = twin.update_from_telemetry(
                raw_telemetry=packet,
                data_provenance=prov,
            )
            all_transitions.extend(transitions)
            if step_delay_s > 0.0:
                time.sleep(step_delay_s)
        return all_transitions

    def create_staleness_scenario(
        self,
        initial_speed: int = 3,
        temp_c: float = 28.0,
        humidity_pct: float = 60.0,
    ) -> List[Dict[str, Any]]:
        """Constructs a sequence transitioning from fresh data to stale data (>300s)."""
        base_time = 1710000000.0  # Deterministic reference timestamp
        return [
            # Packet 1: Normal fresh telemetry
            self.generate_synthetic_telemetry(
                temperature=temp_c,
                humidity=humidity_pct,
                fan_speed=initial_speed,
                timestamp=base_time,
                is_stale=False,
                sensor_age_s=5.0,
            ),
            # Packet 2: Stale telemetry with delay of 360 seconds
            self.generate_synthetic_telemetry(
                temperature=temp_c,
                humidity=humidity_pct,
                fan_speed=initial_speed,
                timestamp=base_time + 360.0,
                is_stale=True,
                sensor_age_s=360.0,
            ),
            # Packet 3: Recovery telemetry
            self.generate_synthetic_telemetry(
                temperature=temp_c,
                humidity=humidity_pct,
                fan_speed=initial_speed,
                timestamp=base_time + 400.0,
                is_stale=False,
                sensor_age_s=2.0,
            ),
        ]

    def create_sensor_dropout_scenario(self) -> List[Dict[str, Any]]:
        """Constructs a sequence simulating partial sensor dropouts (missing light, CO2, etc.)."""
        base_time = 1710001000.0
        return [
            # All sensors present
            self.generate_synthetic_telemetry(
                temperature=26.0,
                humidity=50.0,
                fan_speed=2,
                light=300.0,
                co2=600.0,
                timestamp=base_time,
            ),
            # Drop light and CO2 (residential sensor gap)
            self.generate_synthetic_telemetry(
                temperature=26.5,
                humidity=52.0,
                fan_speed=2,
                light=None,
                co2=None,
                timestamp=base_time + 60.0,
            ),
        ]

    def create_speed_transition_scenario(self) -> List[Dict[str, Any]]:
        """Constructs an operational speed ramp sequence: OFF -> Speed 1 -> Speed 3 -> Speed 5 -> OFF."""
        base_time = 1710002000.0
        speeds = [0, 1, 3, 5, 0]
        sequence = []
        for i, s in enumerate(speeds):
            pkt = self.generate_synthetic_telemetry(
                temperature=27.0 + (i * 0.5),
                humidity=55.0,
                fan_speed=s,
                espent_wh=10.0 + (i * 2.0),
                timestamp=base_time + (i * 60.0),
            )
            sequence.append(pkt)
        return sequence
